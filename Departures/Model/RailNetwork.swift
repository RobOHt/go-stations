import CoreLocation
import MapKit
import SwiftUI

/// A GO rail station from the bundled network file.
struct Station: Identifiable, Hashable {
    let code: String
    let name: String
    let latitude: Double
    let longitude: Double
    let lineCodes: [String]
    let accessible: Bool

    var id: String { code }
    var isUnion: Bool { code == "UN" }
    var coordinate: CLLocationCoordinate2D { CLLocationCoordinate2D(latitude: latitude, longitude: longitude) }
    var location: CLLocation { CLLocation(latitude: latitude, longitude: longitude) }
}

/// A GO rail line with its official colour, track geometry and stop patterns.
struct RailLine: Identifiable {
    /// Code shown to riders (LW, MI, KI, BR, RH, ST, LE).
    let code: String
    /// Code the Metrolinx API uses (Kitchener is still "GT" there).
    let apiCode: String
    let name: String
    let color: Color
    /// Every distinct stop sequence trains on this line run, used to spot express trips.
    let patterns: [[String]]

    var id: String { code }
}

/// One drawable piece of track.
struct TrackPath: Identifiable {
    let id: String
    let lineCode: String
    let color: Color
    let coordinates: [CLLocationCoordinate2D]
}

/// The static rail network bundled with the app (generated by tools/build_network.py from GTFS).
final class RailNetwork {
    static let shared = RailNetwork.loadBundled()

    static let overviewRegion = MKCoordinateRegion(
        center: CLLocationCoordinate2D(latitude: 43.70, longitude: -79.55),
        span: MKCoordinateSpan(latitudeDelta: 0.75, longitudeDelta: 0.95)
    )

    let lines: [RailLine]
    let stations: [Station]
    let trackPaths: [TrackPath]
    let feedVersion: String

    private let stationByCode: [String: Station]
    private let lineByCode: [String: RailLine]

    init(lines: [RailLine], stations: [Station], trackPaths: [TrackPath], feedVersion: String) {
        self.lines = lines
        self.stations = stations
        self.trackPaths = trackPaths
        self.feedVersion = feedVersion
        self.stationByCode = Dictionary(stations.map { ($0.code, $0) }, uniquingKeysWith: { first, _ in first })
        var byCode: [String: RailLine] = [:]
        for line in lines {
            byCode[line.code] = line
            if byCode[line.apiCode] == nil { byCode[line.apiCode] = line }
        }
        self.lineByCode = byCode
    }

    // MARK: Lookups

    func station(_ code: String) -> Station? {
        stationByCode[code.trimmingCharacters(in: .whitespaces)]
    }

    /// Accepts either the rider-facing code (KI) or the API code (GT).
    func line(code: String) -> RailLine? {
        lineByCode[code.trimmingCharacters(in: .whitespaces).uppercased()]
    }

    func line(named name: String) -> RailLine? {
        let wanted = name.trimmingCharacters(in: .whitespaces).lowercased()
        return lines.first { $0.name.lowercased() == wanted }
    }

    func displayLineCode(apiCode: String) -> String {
        line(code: apiCode)?.code ?? apiCode.trimmingCharacters(in: .whitespaces)
    }

    func nearestStation(to location: CLLocation) -> (station: Station, distance: CLLocationDistance)? {
        stations
            .map { ($0, $0.location.distance(from: location)) }
            .min { $0.1 < $1.1 }
            .map { (station: $0.0, distance: $0.1) }
    }

    /// True when the trip skips two or more stations in a row that the line's
    /// all-stops pattern serves. (Matches GO's own "Express To" flags on the Union
    /// feed; single-station skips like Kitchener trains passing Etobicoke North
    /// aren't called express by GO.)
    func isExpress(lineCode: String, stops: [String]) -> Bool {
        guard let line = line(code: lineCode), stops.count >= 2 else { return false }
        for (a, b) in zip(stops, stops.dropFirst()) {
            for pattern in line.patterns {
                guard let i = pattern.firstIndex(of: a) else { continue }
                if let j = pattern[(i + 1)...].firstIndex(of: b), j - i > 2 {
                    return true
                }
            }
        }
        return false
    }

    // MARK: Loading

    private struct File: Decodable {
        struct Line: Decodable {
            let code: String
            let apiCode: String
            let name: String
            let color: String
            let paths: [[[Double]]]
            let patterns: [[String]]
        }

        struct StationEntry: Decodable {
            let code: String
            let name: String
            let lat: Double
            let lon: Double
            let lines: [String]
            let accessible: Bool
        }

        let feedVersion: String
        let lines: [Line]
        let stations: [StationEntry]
    }

    static func loadBundled() -> RailNetwork {
        guard let url = Bundle.main.url(forResource: "network", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let file = try? JSONDecoder().decode(File.self, from: data)
        else {
            assertionFailure("network.json missing or invalid — run tools/build_network.py")
            return RailNetwork(lines: [], stations: [], trackPaths: [], feedVersion: "")
        }

        var lines: [RailLine] = []
        var paths: [TrackPath] = []
        for entry in file.lines {
            let color = Color(hexString: entry.color)
            lines.append(RailLine(code: entry.code, apiCode: entry.apiCode, name: entry.name,
                                  color: color, patterns: entry.patterns))
            for (index, path) in entry.paths.enumerated() {
                let coordinates = path.compactMap { pair -> CLLocationCoordinate2D? in
                    guard pair.count == 2 else { return nil }
                    return CLLocationCoordinate2D(latitude: pair[0], longitude: pair[1])
                }
                paths.append(TrackPath(id: "\(entry.code)-\(index)", lineCode: entry.code,
                                       color: color, coordinates: coordinates))
            }
        }

        let stations = file.stations.map {
            Station(code: $0.code, name: $0.name, latitude: $0.lat, longitude: $0.lon,
                    lineCodes: $0.lines, accessible: $0.accessible)
        }
        return RailNetwork(lines: lines, stations: stations, trackPaths: paths, feedVersion: file.feedVersion)
    }
}

extension Color {
    init(hex: UInt32) {
        self.init(
            red: Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue: Double(hex & 0xFF) / 255
        )
    }

    init(hexString: String) {
        let cleaned = hexString.trimmingCharacters(in: CharacterSet(charactersIn: "# "))
        self.init(hex: UInt32(cleaned, radix: 16) ?? 0x888888)
    }
}

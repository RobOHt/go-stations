/// A GO rail station from the bundled network file.
struct Station: Identifiable, Hashable {
    let code: String
    let name: String
    let latitude: Double
    let longitude: Double
    let lineCodes: [String]
    let accessible: Bool

    var id: String { code }
    var isUnion: Bool { code == "UN" }
    var coordinate: CLLocationCoordinate2D { CLLocationCoordinate2D(latitude: latitude, longitude: longitude) }
    var location: CLLocation { CLLocation(latitude: latitude, longitude: longitude) }
}

/// A GO rail line with its official colour, track geometry and stop patterns.
struct RailLine: Identifiable {
    /// Code shown to riders (LW, MI, KI, BR, RH, ST, LE).
    let code: String
    /// Code the Metrolinx API uses (Kitchener is still "GT" there).
    let apiCode: String
    let name: String
    let color: Color
    /// The colour as hex ("00853E"), for the Live Activity.
    let hex: String
    /// Every distinct stop sequence trains on this line run, used to spot express trips.
    let patterns: [[String]]

    var id: String { code }
}

/// One drawable piece of track.
struct TrackPath: Identifiable {
    let id: String
    let lineCode: String
    let color: Color
    let uiColor: UIColor
    let coordinates: [CLLocationCoordinate2D]
}

/// The static rail network bundled with the app (generated by tools/build_network.py from GTFS).
final class RailNetwork {
    static let shared = RailNetwork.loadBundled()

    static let overviewRegion = MKCoordinateRegion(
        center: CLLocationCoordinate2D(latitude: 43.70, longitude: -79.55),
        span: MKCoordinateSpan(latitudeDelta: 0.75, longitudeDelta: 0.95)
    )

    /// Southern Ontario around the GO network (Niagara to Barrie, Stratford to Oshawa).
    static let serviceArea = MKCoordinateRegion(
        center: CLLocationCoordinate2D(latitude: 43.75, longitude: -79.9),
        span: MKCoordinateSpan(latitudeDelta: 1.7, longitudeDelta: 2.8)
    )

    /// Where the map's centre may go: every station plus a little margin.
    static let cameraCenterLimit = MKCoordinateRegion(
        center: CLLocationCoordinate2D(latitude: 43.75, longitude: -79.93),
        span: MKCoordinateSpan(latitudeDelta: 1.6, longitudeDelta: 2.4)
    )

    /// Widest view allowed, in metres across the screen: about the whole network
    /// (Stratford to Oshawa), so zooming out stops at southern Ontario.
    static let maxVisibleWidth: Double = 190_000

    static func isInServiceArea(_ coordinate: CLLocationCoordinate2D) -> Bool {
        let region = serviceArea
        return abs(coordinate.latitude - region.center.latitude) <= region.span.latitudeDelta / 2
            && abs(coordinate.longitude - region.center.longitude) <= region.span.longitudeDelta / 2
    }

    let lines: [RailLine]
    let stations: [Station]
    let trackPaths: [TrackPath]
    let feedVersion: String

    private let stationByCode: [String: Station]
    private let lineByCode: [String: RailLine]
    /// Each station's neighbours along the lines (consecutive stops of any stop
    /// pattern), with the distance between them in metres.
    private let neighbours: [String: [(code: String, metres: Double)]]

    init(lines: [RailLine], stations: [Station], trackPaths: [TrackPath], feedVersion: String) {
        self.lines = lines
        self.stations = stations
        self.trackPaths = trackPaths
        self.feedVersion = feedVersion
        let stationByCode = Dictionary(stations.map { ($0.code, $0) }, uniquingKeysWith: { first, _ in first })
        self.stationByCode = stationByCode
        var byCode: [String: RailLine] = [:]
        for line in lines {
            byCode[line.code] = line
            if byCode[line.apiCode] == nil { byCode[line.apiCode] = line }
        }
        self.lineByCode = byCode
        var neighbours: [String: [(code: String, metres: Double)]] = [:]
        for line in lines {
            for pattern in line.patterns {
                for (a, b) in zip(pattern, pattern.dropFirst()) {
                    guard let first = stationByCode[a], let second = stationByCode[b] else { continue }
                    let metres = first.location.distance(from: second.location)
                    if !(neighbours[a] ?? []).contains(where: { $0.code == b }) { neighbours[a, default: []].append((b, metres)) }
                    if !(neighbours[b] ?? []).contains(where: { $0.code == a }) { neighbours[b, default: []].append((a, metres)) }
                }
            }
        }
        self.neighbours = neighbours
    }

    // MARK: Lookups

    func station(_ code: String) -> Station? {
        stationByCode[code.trimmingCharacters(in: .whitespaces)]
    }

    /// Accepts either the rider-facing code (KI) or the API code (GT).
    func line(code: String) -> RailLine? {
        lineByCode[code.trimmingCharacters(in: .whitespaces).uppercased()]
    }

    func line(named name: String) -> RailLine? {
        let wanted = name.trimmingCharacters(in: .whitespaces).lowercased()
        return lines.first { $0.name.lowercased() == wanted }
    }

    func displayLineCode(apiCode: String) -> String {
        line(code: apiCode)?.code ?? apiCode.trimmingCharacters(in: .whitespaces)
    }

    /// The station a feed names: "Union Station", "Brampton Innovation District GO",
    /// "Guelph" for Guelph Central and so on.
    func stationNamed(_ name: String) -> Station? {
        func plain(_ text: String) -> String {
            text.lowercased()
                .replacingOccurrences(of: ".", with: "")
                .split(separator: " ")
                .filter { $0 != "go" && $0 != "station" }
                .joined(separator: " ")
        }
        let wanted = plain(name)
        guard !wanted.isEmpty else { return nil }
        if let exact = stations.first(where: { plain($0.name) == wanted }) { return exact }
        let starting = stations.filter { plain($0.name).hasPrefix(wanted + " ") || wanted.hasPrefix(plain($0.name) + " ") }
        if starting.count == 1 { return starting[0] }
        let containing = stations.filter { plain($0.name).contains(wanted) }
        return containing.count == 1 ? containing[0] : nil
    }

    /// How far each station is from `code` along the lines, in metres (stop to stop),
    /// changing trains wherever lines share a station (Union, mostly).
    func distances(to code: String) -> [String: Double] {
        var distance: [String: Double] = [code: 0]
        var done: Set<String> = []
        while let nearest = distance.filter({ !done.contains($0.key) }).min(by: { $0.value < $1.value }) {
            done.insert(nearest.key)
            for next in neighbours[nearest.key] ?? [] where !done.contains(next.code) {
                let through = nearest.value + next.metres
                if through < distance[next.code] ?? .infinity { distance[next.code] = through }
            }
        }
        return distance
    }

    func nearestStation(to location: CLLocation) -> (station: Station, distance: CLLocationDistance)? {
        stations
            .map { ($0, $0.location.distance(from: location)) }
            .min { $0.1 < $1.1 }
            .map { (station: $0.0, distance: $0.1) }
    }

    /// True when the trip skips two or more stations in a row that the line's
    /// all-stops pattern serves. (Matches GO's own "Express To" flags on the Union
    /// feed; single-station skips like Kitchener trains passing Etobicoke North
    /// aren't called express by GO.)
    func isExpress(lineCode: String, stops: [String]) -> Bool {
        guard let line = line(code: lineCode), stops.count >= 2 else { return false }
        for (a, b) in zip(stops, stops.dropFirst()) {
            for pattern in line.patterns {
                guard let i = pattern.firstIndex(of: a) else { continue }
                if let j = pattern[(i + 1)...].firstIndex(of: b), j - i > 2 {
                    return true
                }
            }
        }
        return false
    }

    // MARK: Loading

    private struct File: Decodable {
        struct Line: Decodable {
            let code: String
            let apiCode: String
            let name: String
            let color: String
            let paths: [[[Double]]]
            let patterns: [[String]]
        }

        struct StationEntry: Decodable {
            let code: String
            let name: String
            let lat: Double
            let lon: Double
            let lines: [String]
            let accessible: Bool
        }

        let feedVersion: String
        let lines: [Line]
        let stations: [StationEntry]
    }

    static func loadBundled() -> RailNetwork {
        guard let url = Bundle.main.url(forResource: "network", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let file = try? JSONDecoder().decode(File.self, from: data)
        else {
            assertionFailure("network.json missing or invalid — run tools/build_network.py")
            return RailNetwork(lines: [], stations: [], trackPaths: [], feedVersion: "")
        }

        var lines: [RailLine] = []
        var paths: [TrackPath] = []
        for entry in file.lines {
            let color = Color(hexString: entry.color)
            lines.append(RailLine(code: entry.code, apiCode: entry.apiCode, name: entry.name,
                                  color: color, hex: entry.color, patterns: entry.patterns))
            for (index, path) in entry.paths.enumerated() {
                let coordinates = path.compactMap { pair -> CLLocationCoordinate2D? in
                    guard pair.count == 2 else { return nil }
                    return CLLocationCoordinate2D(latitude: pair[0], longitude: pair[1])
                }
                paths.append(TrackPath(id: "\(entry.code)-\(index)", lineCode: entry.code,
                                       color: color, uiColor: UIColor(hexString: entry.color),
                                       coordinates: coordinates))
            }
        }

        let stations = file.stations.map {
            Station(code: $0.code, name: $0.name, latitude: $0.lat, longitude: $0.lon,
                    lineCodes: $0.lines, accessible: $0.accessible)
        }
        return RailNetwork(lines: lines, stations: stations, trackPaths: paths, feedVersion: file.feedVersion)
    }
}

/// On your home or work station's board: the trains that take you toward the other
/// one, whether straight there or to where you change (Union, say).
struct CommuteDirection: Sendable {
    /// The board's station.
    let from: String
    /// Your other station, where the trains shown head.
    let toward: String
    private let distances: [String: Double]

    init?(from: String, toward: String, network: RailNetwork = .shared) {
        let distances = network.distances(to: toward)
        guard from != toward, distances[from] != nil else { return nil }
        self.from = from
        self.toward = toward
        self.distances = distances
    }

    /// Whether this train takes you that way: it stops there, or the first of its
    /// stops the network knows is closer to it along the lines than this station.
    /// A train whose stops aren't known is kept, so none is hidden on a guess.
    func includes(_ row: BoardRow) -> Bool {
        includes(stopCodes: row.stopCodes)
    }

    /// The same for a train's stops after this station, as codes.
    func includes(stopCodes codes: [String]?) -> Bool {
        guard let codes, !codes.isEmpty else { return true }
        if codes.contains(toward) { return true }
        guard let here = distances[from], let next = codes.lazy.compactMap({ distances[$0] }).first
        else { return true }
        return next < here
    }
}

extension Color {
    init(hex: UInt32) {
        self.init(
            red: Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue: Double(hex & 0xFF) / 255
        )
    }

    init(hexString: String) {
        let cleaned = hexString.trimmingCharacters(in: CharacterSet(charactersIn: "# "))
        self.init(hex: UInt32(cleaned, radix: 16) ?? 0x888888)
    }
}

extension UIColor {
    convenience init(hexString: String) {
        let cleaned = hexString.trimmingCharacters(in: CharacterSet(charactersIn: "# "))
        let hex = UInt32(cleaned, radix: 16) ?? 0x888888
        self.init(
            red: CGFloat((hex >> 16) & 0xFF) / 255,
            green: CGFloat((hex >> 8) & 0xFF) / 255,
            blue: CGFloat(hex & 0xFF) / 255,
            alpha: 1
        )
    }
}
